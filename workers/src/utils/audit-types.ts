  AUTH_TOKEN_REFRESH = 'AUTH_TOKEN_REFRESH',
  AUTH_SESSION_CREATED = 'AUTH_SESSION_CREATED',
  AUTH_SESSION_DESTROYED = 'AUTH_SESSION_DESTROYED',
  AUTH_SESSION_VALIDATED = 'AUTH_SESSION_VALIDATED',
  AUTH_SESSION_EXPIRED = 'AUTH_SESSION_EXPIRED',
  AUTH_SESSION_INVALID = 'AUTH_SESSION_INVALID',
  AUTH_SESSION_ACCESS = 'AUTH_SESSION_ACCESS',
  AUTH_FLOW_INITIATED = 'AUTH_FLOW_INITIATED',
  
  // State management events
  STATE_CREATED = 'STATE_CREATED',
  STATE_VALIDATED = 'STATE_VALIDATED',
  STATE_DELETED = 'STATE_DELETED',
  STATE_INVALID = 'STATE_INVALID',
  
  // Data access events
  DATA_ACCESS_READ = 'DATA_ACCESS_READ',
  DATA_ACCESS_WRITE = 'DATA_ACCESS_WRITE',
  DATA_ACCESS_DELETE = 'DATA_ACCESS_DELETE',
  DATA_ACCESS_DENIED = 'DATA_ACCESS_DENIED',
  
  // Data security events
  DATA_ENCRYPTION = 'DATA_ENCRYPTION',
  DATA_DECRYPTION = 'DATA_DECRYPTION',
  
  // Security events
  SECURITY_SUSPICIOUS_ACTIVITY = 'SECURITY_SUSPICIOUS_ACTIVITY',
  SECURITY_RATE_LIMIT_EXCEEDED = 'SECURITY_RATE_LIMIT_EXCEEDED',
  CORS_VIOLATION = 'CORS_VIOLATION',
