export enum LogLevel {
  INFO = 'INFO',
  WARN = 'WARN',
  ERROR = 'ERROR',
}

export interface AuditLogEntry {
  timestamp: string;
  eventType: AuditEventType;
  level: LogLevel;
  userId?: string;
  sessionId?: string;
  correlationId: string;
  ipAddress?: string;
  userAgent?: string;
  resource?: string;
  action?: string;
  result: 'success' | 'failure';
  metadata?: Record<string, any>;
}